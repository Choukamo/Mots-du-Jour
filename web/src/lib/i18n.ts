export type Key = keyof typeof fr
const dict = { fr, zh }

export function makeT(lang: Lang) {
  return (key: Key, vars: Record<string, string | number> = {}) =>
    dict[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

export function fmtDate(iso: string, lang: Lang, tz?: string) {
  return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'zh-CN', { weekday: 'long', day: 'numeric', month: 'long', timeZone: tz }).format(new Date(iso))
}
